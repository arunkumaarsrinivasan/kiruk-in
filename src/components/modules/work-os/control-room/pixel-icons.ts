/** A project's 16×12 picture. */
export function iconRows(projectId: string): readonly string[] {
  return ICONS[projectId] ?? SHEET;
}

/** Turn a picture a quarter turn clockwise. */
function turned(rows: readonly string[]): string[] {
  const h = rows.length;
  const w = rows[0].length;
  return Array.from({ length: w }, (_, y) => Array.from({ length: h }, (_, x) => rows[h - 1 - x][y]).join(""));
}

